// Bundles src/ into ONE self-contained index.html (three.js included), so the
// game runs offline, from file://, from GitHub Pages and on phones.
import * as esbuild from 'esbuild';
import fs from 'fs';

const watch = process.argv.includes('--watch');

// Generate src/assets/registry.js: every file in assets/ becomes an embedded
// data URL (single-file build keeps working offline / from file://).
function writeRegistry() {
  const groups = {};
  const walk = (dir, rel = '') => {
    if (!fs.existsSync(dir)) return;
    for (const f of fs.readdirSync(dir)) {
      const full = dir + '/' + f;
      if (fs.statSync(full).isDirectory()) walk(full, rel + f + '/');
      else if (/\.(glb|webp|mp3|jpg|png)$/.test(f)) {
        const group = rel.replace(/\/$/, '') || 'root';
        (groups[group] = groups[group] || []).push({ name: f.replace(/\.\w+$/, ''), file: rel + f });
      }
    }
  };
  walk('assets');
  let src = '// AUTO-GENERATED by build.mjs from /assets. Do not edit.\n';
  let i = 0; const lines = [];
  for (const g in groups) {
    const entries = groups[g].map((e) => { const v = 'a' + (i++); src += `import ${v} from '../../assets/${e.file}';\n`; return `  ${JSON.stringify(e.name)}: ${v},`; });
    lines.push(`export const ${g.replace(/\W/g, '_')} = {\n${entries.join('\n')}\n};`);
  }
  src += lines.join('\n') + '\n';
  fs.mkdirSync('src/assets', { recursive: true });
  const p = 'src/assets/registry.js';
  if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== src) fs.writeFileSync(p, src);
}
writeRegistry();

function inline(js) {
  const css = fs.readFileSync('src/style.css', 'utf8');
  const tpl = fs.readFileSync('src/index.html', 'utf8');
  const safeJs = js.replace(/<\/script/gi, '<\\/script');
  return tpl.replace('/*__CSS__*/', () => css).replace('/*__JS__*/', () => safeJs);
}

const plugin = {
  name: 'inline-html',
  setup(build) {
    build.onEnd((res) => {
      if (res.errors.length) return;
      const js = res.outputFiles.find((f) => f.path.endsWith('.js')).text;
      fs.writeFileSync('index.html', inline(js));
      const kb = (fs.statSync('index.html').size / 1024).toFixed(0);
      console.log(`[build] index.html written (${kb} KB)`);
    });
  },
};

const opts = {
  entryPoints: ['src/main.js'],
  bundle: true,
  minify: !watch,
  sourcemap: false,
  format: 'iife',
  target: 'es2020',
  write: false,
  outfile: 'out.js',
  legalComments: 'none',
  loader: { '.glb': 'dataurl', '.webp': 'dataurl', '.mp3': 'dataurl', '.jpg': 'dataurl', '.png': 'dataurl' },
  plugins: [plugin],
};

if (watch) {
  const ctx = await esbuild.context(opts);
  await ctx.watch();
  console.log('[build] watching src/ ...');
} else {
  await esbuild.build(opts);
}
